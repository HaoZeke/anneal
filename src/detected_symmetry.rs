    /// A centred icosahedron: the centre and its twelve vertices.
    fn icosahedron(scale: f64) -> Array1<f64> {
        let phi = (1.0 + 5.0_f64.sqrt()) / 2.0;
        let norm = (1.0 + phi * phi).sqrt();
        let (a, b) = (scale / norm, scale * phi / norm);
        let mut out = vec![0.0; 3];
        for s in [-1.0, 1.0] {
            for t in [-1.0, 1.0] {
                out.extend([0.0, s * a, t * b]);
                out.extend([s * a, t * b, 0.0]);
                out.extend([t * b, 0.0, s * a]);
            }
        }
        Array1::from(out)
    }

    fn jitter(x: &Array1<f64>, amplitude: f64) -> Array1<f64> {
        jitter_seeded(x, amplitude, 0)
    }

    fn jitter_seeded(x: &Array1<f64>, amplitude: f64, seed: u64) -> Array1<f64> {
        let mut y = x.clone();
        for (i, v) in y.iter_mut().enumerate() {
            let k = (i as u64 * 37 + 11 + 29 * seed) % 17;
            *v += amplitude * (k as f64 / 8.0 - 1.0);
        }
        y
    }

