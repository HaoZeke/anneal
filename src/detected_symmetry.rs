    /// The four-at-a-time scan over the sites finds the site the scan in order
    /// finds, through merges that move sites, with images at the reach and a
    /// rounding step beyond it, and with coordinates that are not numbers.
    #[test]
    fn the_cleared_scan_finds_the_site_the_scan_in_order_finds() {
        let cutoff = 0.3;
        for poisoned in [false, true] {
            let mut set = SiteSet::new();
            let mut merged = 0;
            let mut opened = 0;
            for k in 0..2500 {
                let t = k as f64;
                let mut w = [
                    cutoff * 5.0 * (t * 0.37).sin(),
                    cutoff * 5.0 * (t * 0.73).cos(),
                    cutoff * 5.0 * (t * 0.11).sin(),
                ];
                if k % 7 == 0 {
                    w[0] = (k % 5) as f64 * cutoff;
                }
                if k % 11 == 0 {
                    w[1] = (k % 5) as f64 * cutoff * (1.0 + 4.0 * f64::EPSILON);
                }
                if poisoned && k % 97 == 3 {
                    w[k % 3] = [f64::NAN, f64::INFINITY, f64::NEG_INFINITY][k % 3];
                }
                let want = first_site_within(&set.sites, w, cutoff);
                assert_eq!(set.first_within(w, cutoff), want, "image {k}");
                match want {
                    Some(i) => {
                        set.merge(i, w);
                        merged += 1;
                    }
                    None => {
                        set.push(w);
                        opened += 1;
                    }
                }
            }
            assert!(merged > 100 && opened > 100, "{merged} {opened}");
        }
    }

    /// The pairs come out as a stable sort on the distance gives them, with
    /// many equal distances and with a distance that is not a number.
    #[test]
    fn the_pairs_come_in_the_order_of_a_stable_sort() {
        for (m, quantum) in [(1usize, 0.0), (7, 3.0), (30, 5.0), (30, 0.0)] {
            let mut pairs = Vec::new();
            for k in 0..m {
                for i in 0..m {
                    let t = (k * 31 + i * 17 + 5) as f64;
                    let d = (t * 0.618).fract() * 10.0;
                    pairs.push((
                        if quantum > 0.0 {
                            (d / quantum).floor()
                        } else {
                            d
                        },
                        k,
                        i,
                    ));
                }
            }
            let mut stable = pairs.clone();
            stable.sort_by(|p, q| p.0.partial_cmp(&q.0).unwrap_or(std::cmp::Ordering::Equal));
            sort_pairs(&mut pairs);
            assert_eq!(pairs, stable);
        }
        let mut pairs = vec![(2.0, 0, 0), (f64::NAN, 0, 1), (1.0, 1, 0), (2.0, 1, 1)];
        let mut stable = pairs.clone();
        stable.sort_by(|p, q| p.0.partial_cmp(&q.0).unwrap_or(std::cmp::Ordering::Equal));
        sort_pairs(&mut pairs);
        for (g, w) in pairs.iter().zip(&stable) {
            assert_eq!((g.1, g.2), (w.1, w.2));
        }
    }

    /// The completion is the one that scans the sites in order and sorts
    /// every pair, bit for bit, on structures whose sites merge a lot and
    /// whose assignment has to look past the first pairs.
    #[test]
    fn the_completion_is_the_one_the_plain_scan_and_sort_give() {
        let mut checked = 0;
        for (x, classes) in [
            (jitter(&icosahedron(1.0), 0.02), None),
            (jitter(&icosahedron(1.0), 0.12), None),
            (jitter(&octahedron(), 0.1), None),
            (jitter(&zincblende().0, 0.08), Some(zincblende().1)),
        ] {
            let n = x.len() / 3;
            let centre = centroid(x.view(), n);
            for tolerance in [0.1, 0.3, 0.6] {
                let Some(group) =
                    detected_group_classed(x.view(), n, classes.as_deref(), tolerance)
                else {
                    continue;
                };
                for cutoff in [0.1, 0.3, 0.8] {
                    let got = complete_orbits_classed(
                        x.view(),
                        n,
                        classes.as_deref(),
                        &group,
                        centre,
                        cutoff,
                        0.05,
                    );
                    let want = plain_completion(
                        x.view(),
                        n,
                        classes.as_deref(),
                        &group,
                        centre,
                        cutoff,
                        0.05,
                    );
                    assert_eq!(
                        got.as_ref()
                            .map(|v| v.iter().map(|a| a.to_bits()).collect::<Vec<_>>()),
                        want.as_ref()
                            .map(|v| v.iter().map(|a| a.to_bits()).collect::<Vec<_>>())
                    );
                    checked += usize::from(got.is_some());
                }
            }
        }
        assert!(checked > 5, "{checked}");
    }

    fn plain_completion(
        x: ArrayView1<f64>,
        n: usize,
        classes: Option<&[u32]>,
        group: &[Rot],
        centre: [f64; 3],
        pair_cutoff: f64,
        min_separation: f64,
    ) -> Option<Array1<f64>> {
        let parts = class_members(classes, n).unwrap_or_else(|| vec![(0..n).collect()]);
        let rel = |a: usize| -> [f64; 3] {
            [
                x[3 * a] - centre[0],
                x[3 * a + 1] - centre[1],
                x[3 * a + 2] - centre[2],
            ]
        };
        let mut taken: Vec<[f64; 3]> = Vec::with_capacity(n);
        let mut out = x.to_owned();
        let mut moved = false;
        for members in &parts {
            let m = members.len();
            let mut sites: Vec<([f64; 3], usize)> = Vec::new();
            for &a in members {
                let r = rel(a);
                for g in group {
                    let w = apply(g, r);
                    match first_site_within(&sites, w, pair_cutoff) {
                        Some(i) => {
                            let (p, count) = &mut sites[i];
                            let c = *count as f64;
                            for k in 0..3 {
                                p[k] = (p[k] * c + w[k]) / (c + 1.0);
                            }
                            *count += 1;
                        }
                        None => sites.push((w, 1)),
                    }
                }
            }
            sites.sort_by(|p, q| {
                q.1.cmp(&p.1).then_with(|| {
                    let rp = p.0.iter().map(|v| v * v).sum::<f64>();
                    let rq = q.0.iter().map(|v| v * v).sum::<f64>();
                    rp.partial_cmp(&rq).unwrap_or(std::cmp::Ordering::Equal)
                })
            });
            let mut chosen: Vec<[f64; 3]> = Vec::with_capacity(m);
            for (p, _) in &sites {
                if chosen.len() == m {
                    break;
                }
                let clear = chosen.iter().chain(taken.iter()).all(|q| {
                    ((p[0] - q[0]).powi(2) + (p[1] - q[1]).powi(2) + (p[2] - q[2]).powi(2)).sqrt()
                        >= min_separation
                });
                if clear {
                    chosen.push(*p);
                }
            }
            if chosen.len() < m {
                return None;
            }
            let mut pairs: Vec<(f64, usize, usize)> = Vec::with_capacity(m * m);
            for (k, &a) in members.iter().enumerate() {
                let r = rel(a);
                for (i, p) in chosen.iter().enumerate() {
                    let d2 = (r[0] - p[0]).powi(2) + (r[1] - p[1]).powi(2) + (r[2] - p[2]).powi(2);
                    pairs.push((d2, k, i));
                }
            }
            pairs.sort_by(|p, q| p.0.partial_cmp(&q.0).unwrap_or(std::cmp::Ordering::Equal));
            let mut atom_done = vec![false; m];
            let mut site_done = vec![false; m];
            let mut assigned = 0;
            for (d, k, i) in pairs {
                if atom_done[k] || site_done[i] {
                    continue;
                }
                atom_done[k] = true;
                site_done[i] = true;
                assigned += 1;
                let a = members[k];
                for c in 0..3 {
                    out[3 * a + c] = centre[c] + chosen[i][c];
                }
                if d.sqrt() > 1e-9 {
                    moved = true;
                }
                if assigned == m {
                    break;
                }
            }
            taken.extend(chosen);
        }
        moved.then_some(out)
    }

    /// A framework whose species are all different has no operation that
    /// keeps every point on a point of its own species, so the group read by
    /// species is trivial and nothing is completed. Read from the points it
    /// is the framework's, and each species still has its own sites: every
    /// atom of a class of one point is seated within the merge radius of an
    /// image of itself under the group, and no two atoms overlap.
    #[test]
    fn the_framework_reading_completes_what_the_species_reading_cannot() {
        for amplitude in [0.02, 0.05] {
            let x = jitter(&icosahedron(1.0), amplitude);
            let n = x.len() / 3;
            let classes: Vec<u32> = (0..n as u32).collect();
            let tolerance = 0.25;
            let merge = 0.3;
            assert!(
                complete_detected_classed(x.view(), n, Some(&classes), tolerance, merge, 1.0, 0.1)
                    .is_none()
            );
            let y = complete_detected_framework(
                x.view(),
                n,
                Some(&classes),
                tolerance,
                merge,
                1.0,
                0.1,
            )
            .expect("the framework of a jittered icosahedron completes");
            let group = detected_group_classed(x.view(), n, None, tolerance)
                .expect("the framework has a group");
            let centre = centroid(x.view(), n);
            for a in 0..n {
                let r = [
                    x[3 * a] - centre[0],
                    x[3 * a + 1] - centre[1],
                    x[3 * a + 2] - centre[2],
                ];
                let near_an_image = group.iter().any(|g| {
                    let w = apply(g, r);
                    (0..3)
                        .map(|k| (centre[k] + w[k] - y[3 * a + k]).powi(2))
                        .sum::<f64>()
                        .sqrt()
                        <= merge
                });
                assert!(near_an_image, "{amplitude} atom {a}");
            }
            for a in 0..n {
                for b in (a + 1)..n {
                    let gap: f64 = (0..3)
                        .map(|k| (y[3 * a + k] - y[3 * b + k]).powi(2))
                        .sum::<f64>()
                        .sqrt();
                    assert!(gap >= 0.1, "{a} {b} {gap}");
                }
            }
        }
    }

    /// The closure of loosely commensurate generators is cut at its cap, and
    /// some of what it holds are words the core does not carry. The group of
    /// the fitted reading is the plain group less exactly those: every element
    /// kept deviates by less than the tolerance, every element dropped by no
    /// less, and the identity stays first.
    #[test]
    fn the_fitted_group_has_only_operations_the_core_carries() {
        for (amplitude, tolerance) in [(0.15, 0.25), (0.3, 0.5)] {
            let x = jitter(&icosahedron(1.0), amplitude);
            let n = x.len() / 3;
            let plain = read_group(x.view(), n, None, tolerance, false).expect("a loose group");
            let kept = read_group(x.view(), n, None, tolerance, true).expect("a symmetric part");
            assert_eq!(
                plain.len(),
                LARGEST_POLYHEDRAL_GROUP,
                "{amplitude}: the cut"
            );
            assert!(kept.len() < plain.len(), "{amplitude}: nothing was dropped");
            assert_eq!(kept[0], plain[0]);
            let deviation =
                |g: &Rot| operation_deviation(x.view(), n, None, g, f64::INFINITY).expect("no cap");
            for g in &plain {
                let held = kept.contains(g);
                assert_eq!(
                    held,
                    deviation(g) < tolerance,
                    "{amplitude}: {}",
                    deviation(g)
                );
            }
        }
    }

