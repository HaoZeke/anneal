"""Number the labels of the manuscript and of the Supporting Information for the other document.

The two documents are built apart, so neither can read the other's aux file. This script
numbers each label from the TeX source the way achemso does and writes
labels-manuscript.tex, read by \\msref in the SI, and labels-si.tex, read by \\siref in the
manuscript. --check fails on a stale file, and --aux DIR compares the numbers with the aux
files of a build in DIR.

    python3 paper/jctc/scripts/cross_labels.py [--check] [--aux DIR]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

JCTC = Path(__file__).resolve().parent.parent
DOCUMENTS = {"manuscript": ("ms", ""), "si": ("si", "S")}
TOKEN = re.compile(r"\\(sub)?section(\*?)\{|\\(begin|end)\{(equation|figure|table)\*?\}|\\label\{([^}]*)\}")


def uncomment(text: str) -> str:
    return "\n".join(re.sub(r"(?<!\\)%.*", "", line) for line in text.splitlines())


def numbers(text: str, prefix: str) -> dict[str, str]:
    """Each label and the number achemso prints for it: a float or equation it sits in, else its section."""
    section = subsection = 0
    counters = {"equation": 0, "figure": 0, "table": 0}
    current, inside, labels = "", [], {}
    for m in TOKEN.finditer(uncomment(text)):
        sub, star, edge, environment, label = m.groups()
        if label is not None:
            labels[label] = f"{prefix}{counters[inside[-1]]}" if inside else current
        elif edge == "begin":
            counters[environment] += 1
            inside.append(environment)
        elif edge == "end":
            inside.pop()
        elif not star:
            if sub:
                subsection += 1
            else:
                section, subsection = section + 1, 0
            current = f"{prefix}{section}.{subsection}" if sub else f"{prefix}{section}"
    return labels


def labels(document: str) -> dict[str, str]:
    _, prefix = DOCUMENTS[document]
    return numbers((JCTC / f"{document}.tex").read_text(), prefix)


def labels_text(document: str) -> str:
    name, _ = DOCUMENTS[document]
    lines = [f"% Generated by scripts/cross_labels.py from {document}.tex; do not edit."]
    lines += [f"\\expandafter\\def\\csname {name}@{label}\\endcsname{{{number}}}"
              for label, number in sorted(labels(document).items())]
    return "\n".join(lines) + "\n"


def stale() -> list[str]:
    return [f"labels-{document}.tex" for document in DOCUMENTS
            if not (JCTC / f"labels-{document}.tex").is_file()
            or (JCTC / f"labels-{document}.tex").read_text() != labels_text(document)]


def aux_mismatches(directory: Path) -> list[str]:
    """Labels whose number in the aux file of a build differs from the number parsed here."""
    found = []
    for document in DOCUMENTS:
        aux = dict(re.findall(r"\\newlabel\{([^}]*)\}\{\{([^}]*)\}", (directory / f"{document}.aux").read_text()))
        found += [f"{document}:{label} parsed {number}, built {aux.get(label)}"
                  for label, number in labels(document).items() if aux.get(label) != number]
    return found


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a committed labels file is stale")
    parser.add_argument("--aux", type=Path, help="compare with the aux files of a build in this directory")
    parser.add_argument("--output", type=Path, help="write the label files in this directory")
    args = parser.parse_args(argv)
    if args.output:
        args.output.mkdir(parents=True, exist_ok=True)
        for document in DOCUMENTS:
            dest = args.output / f"labels-{document}.tex"
            if dest.exists():
                raise SystemExit(f"refusing to overwrite {dest}")
            dest.write_text(labels_text(document))
        return 0
    if args.aux:
        mismatches = aux_mismatches(args.aux)
        for mismatch in mismatches:
            print(mismatch, file=sys.stderr)
        return 1 if mismatches else 0
    if args.check:
        files = stale()
        for path in files:
            print(f"cross_labels: {path} is stale", file=sys.stderr)
        return 1 if files else 0
    for document in DOCUMENTS:
        (JCTC / f"labels-{document}.tex").write_text(labels_text(document))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
